create table if not exists public.dm_conversations (
  id uuid primary key default gen_random_uuid(),
  user_one uuid not null references auth.users(id) on delete cascade,
  user_two uuid not null references auth.users(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint dm_conversations_distinct_users check (user_one <> user_two),
  constraint dm_conversations_sorted_users check (user_one < user_two),
  constraint dm_conversations_creator_is_member check (created_by = user_one or created_by = user_two),
  constraint dm_conversations_pair_unique unique (user_one, user_two)
);
create table if not exists public.dm_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.dm_conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  content varchar(2000) not null,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  constraint dm_messages_content_length check (length(btrim(content)) between 1 and 2000)
);
create index if not exists dm_messages_conversation_created_idx
  on public.dm_messages(conversation_id, created_at desc, id desc);
alter table public.dm_conversations enable row level security;
alter table public.dm_messages enable row level security;
alter table public.dm_messages replica identity full;
grant select, insert on public.dm_conversations to authenticated;
grant select, insert, update, delete on public.dm_messages to authenticated;
drop policy if exists "DM members can view their conversations" on public.dm_conversations;
create policy "DM members can view their conversations"
on public.dm_conversations for select to authenticated
using ((select auth.uid()) = user_one or (select auth.uid()) = user_two);
drop policy if exists "Users can create conversations they belong to" on public.dm_conversations;
create policy "Users can create conversations they belong to"
on public.dm_conversations for insert to authenticated
with check (
  created_by = (select auth.uid())
  and ((select auth.uid()) = user_one or (select auth.uid()) = user_two)
);
drop policy if exists "DM members can read messages" on public.dm_messages;
create policy "DM members can read messages"
on public.dm_messages for select to authenticated
using (exists (
  select 1 from public.dm_conversations c
  where c.id = dm_messages.conversation_id
    and ((select auth.uid()) = c.user_one or (select auth.uid()) = c.user_two)
));
drop policy if exists "DM members can send their own messages" on public.dm_messages;
create policy "DM members can send their own messages"
on public.dm_messages for insert to authenticated
with check (
  sender_id = (select auth.uid())
  and exists (
    select 1 from public.dm_conversations c
    where c.id = dm_messages.conversation_id
      and ((select auth.uid()) = c.user_one or (select auth.uid()) = c.user_two)
  )
);
drop policy if exists "Authors can edit their own DM messages" on public.dm_messages;
create policy "Authors can edit their own DM messages"
on public.dm_messages for update to authenticated
using (sender_id = (select auth.uid()))
with check (
  sender_id = (select auth.uid())
  and exists (
    select 1 from public.dm_conversations c
    where c.id = dm_messages.conversation_id
      and ((select auth.uid()) = c.user_one or (select auth.uid()) = c.user_two)
  )
);
drop policy if exists "Authors can delete their own DM messages" on public.dm_messages;
create policy "Authors can delete their own DM messages"
on public.dm_messages for delete to authenticated
using (sender_id = (select auth.uid()));
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'dm_messages'
  ) then
    alter publication supabase_realtime add table public.dm_messages;
  end if;
end $$;
